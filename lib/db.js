// Venue Diary — database layer on PostgreSQL (via `pg`), targeting Neon.
// One DATABASE_URL drives both local dev and Vercel production. Everything is
// async. Chosen for a large multi-client scope (mobile app + dashboard + more):
// Postgres scales, and the double-booking guard uses a partial unique index now
// (upgradeable to an EXCLUDE constraint per TECHNICAL_PLAN.md).

import pg from 'pg';
import crypto from 'node:crypto';

const { Pool } = pg;

if (!process.env.DATABASE_URL) {
  console.warn('  [db] DATABASE_URL is not set — create a .env with your Neon connection string.');
}

export const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.DATABASE_URL && !process.env.DATABASE_URL.includes('localhost')
    ? { rejectUnauthorized: false }
    : undefined,
  max: 3,
});

